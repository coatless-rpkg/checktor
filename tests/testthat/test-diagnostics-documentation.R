        "  Sys.sleep(60)",
        "}",
        "}"
      ),
      "slow_and_network.Rd" = c(
        "\\name{slow_and_network}",
        "\\alias{slow_and_network}",
        "\\title{n}",
        "\\description{d}",
        "\\value{x}",
        "\\examples{",
        "\\dontrun{",
